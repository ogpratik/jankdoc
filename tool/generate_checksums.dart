/// Update packages/jankdoc/assets/binary_checksums.json with the SHA-256 of
/// each daemon archive (`jankdoc-daemon-<version>-<platform>.tar.gz`).
///
/// From a published release (the normal path — release.yaml uploads a
/// `.sha256` next to every archive; needs the `gh` CLI):
///   dart run tool/generate_checksums.dart --release daemon-v1.0.0
///
/// From local builds in dist/binaries/ (tool/build_binaries.sh):
///   dart run tool/generate_checksums.dart
///
/// Platforms with no archive keep their existing value. DaemonLauncher only
/// downloads for platforms that have a checksum, so an empty entry means
/// "use the dart run fallback".
library;

import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

const _platforms = ['macos-arm64', 'macos-x64', 'linux-x64', 'windows-x64'];

Future<void> main(List<String> args) async {
  final repoRoot = File.fromUri(Platform.script).parent.parent.path;
  final checksumFile =
      File('$repoRoot/packages/jankdoc/assets/binary_checksums.json');
  final version = _daemonVersion(repoRoot);

  final releaseIndex = args.indexOf('--release');
  final found = releaseIndex >= 0 && releaseIndex + 1 < args.length
      ? await _fromRelease(args[releaseIndex + 1], version)
      : _fromLocalBuilds('$repoRoot/dist/binaries', version);

  final existing = checksumFile.existsSync()
      ? jsonDecode(checksumFile.readAsStringSync()) as Map<String, dynamic>
      : <String, dynamic>{};
  final binaries = {
    for (final p in _platforms) p: '',
    ...?(existing['binaries'] as Map<String, dynamic>?),
    ...found,
  };

  final manifest = {
    '_comment': 'SHA-256 of each jankdoc-daemon-<version>-<platform>.tar.gz. '
        'Generated by tool/generate_checksums.dart. Do not edit by hand.',
    'version': version,
    'binaries': binaries,
  };
  checksumFile.writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(manifest)}\n',
  );

  for (final MapEntry(:key, :value) in found.entries) {
    stdout.writeln('[checksums] ✓ $key  $value');
  }
  stdout.writeln('[checksums] wrote ${checksumFile.path}');
  if (found.isEmpty) {
    stderr.writeln('[checksums] no archives found — nothing updated.');
    exit(1);
  }
}

/// The version DaemonLauncher downloads (`_kDaemonVersion`), which is
/// independent of the pub package version.
String _daemonVersion(String repoRoot) {
  final src = File('$repoRoot/packages/jankdoc/lib/src/daemon_launcher.dart')
      .readAsStringSync();
  return RegExp(r"^const _kDaemonVersion\s*=\s*'([^']+)';", multiLine: true)
      .firstMatch(src)!
      .group(1)!;
}

String _archive(String version, String platform) =>
    'jankdoc-daemon-$version-$platform.tar.gz';

Map<String, String> _fromLocalBuilds(String dir, String version) => {
      for (final p in _platforms)
        if (File('$dir/${_archive(version, p)}') case final f
            when f.existsSync())
          p: sha256.convert(f.readAsBytesSync()).toString(),
    };

Future<Map<String, String>> _fromRelease(String tag, String version) async {
  final tmp = Directory.systemTemp.createTempSync('jankdoc_checksums');
  try {
    final r = await Process.run('gh', [
      'release', 'download', tag, //
      '--pattern', '*.sha256', '--dir', tmp.path,
    ]);
    if (r.exitCode != 0) {
      stderr.writeln('[checksums] gh release download failed: ${r.stderr}');
      exit(1);
    }
    return {
      for (final p in _platforms)
        if (File('${tmp.path}/${_archive(version, p)}.sha256') case final f
            when f.existsSync())
          p: f.readAsStringSync().trim().split(RegExp(r'\s+')).first,
    };
  } finally {
    tmp.deleteSync(recursive: true);
  }
}
