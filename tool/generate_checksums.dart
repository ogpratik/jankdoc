/// Update packages/jankdoc/assets/binary_checksums.json from built binaries.
///
/// Run after `tool/build_binaries.sh` has produced binaries in `dist/binaries/`
/// on all supported platforms. This script reads the binaries from `dist/binaries/`,
/// computes their SHA-256 checksums, and writes them into the asset file.
///
/// Run from the repo root:
///   dart run tool/generate_checksums.dart
///
/// Supports partial updates: if a platform binary is missing (e.g. you only
/// built on macOS), only the present platforms are updated in the JSON. The
/// others retain their existing values.
library;

import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

Future<void> main(List<String> args) async {
  final repoRoot = _repoRoot();
  final binDir = Directory('$repoRoot/dist/binaries');
  final checksumFile =
      File('$repoRoot/packages/jankdoc/assets/binary_checksums.json');

  if (!binDir.existsSync()) {
    stderr.writeln(
      '[checksums] dist/binaries/ not found. '
      'Run tool/build_binaries.sh first.',
    );
    exit(1);
  }

  // Read the pubspec version.
  final pubspec = File('$repoRoot/packages/jankdoc/pubspec.yaml').readAsStringSync();
  final versionMatch = RegExp(r'^version:\s*(.+)$', multiLine: true).firstMatch(pubspec);
  final version = versionMatch?.group(1)?.trim() ?? 'unknown';

  // Read existing checksums (preserve untouched platforms).
  var existing = <String, dynamic>{
    '_comment':
        'SHA-256 checksums for pre-compiled daemon binaries. '
        'Auto-generated by tool/generate_checksums.dart. Do not edit by hand.',
    'version': version,
    'binaries': {
      'macos-arm64': '',
      'macos-x64': '',
      'linux-x64': '',
      'windows-x64': '',
    },
  };
  if (checksumFile.existsSync()) {
    try {
      existing = jsonDecode(checksumFile.readAsStringSync()) as Map<String, dynamic>;
      existing['version'] = version;
    } on FormatException {
      // Malformed JSON — overwrite.
    }
  }

  final binaries = Map<String, dynamic>.from(
    existing['binaries'] as Map<String, dynamic>? ?? {},
  );

  // Find and hash all binaries in dist/binaries/.
  final platforms = ['macos-arm64', 'macos-x64', 'linux-x64', 'windows-x64'];
  var updated = 0;

  for (final platform in platforms) {
    final ext = platform.startsWith('windows') ? '.exe' : '';
    final binaryFile =
        File('${binDir.path}/jankdoc-daemon-$platform$ext');
    if (!binaryFile.existsSync()) {
      stdout.writeln('[checksums] skipping $platform (not found)');
      continue;
    }
    final bytes = binaryFile.readAsBytesSync();
    final checksum = sha256.convert(bytes).toString();
    binaries[platform] = checksum;
    stdout.writeln('[checksums] ✓ $platform  $checksum');
    updated++;
  }

  existing['binaries'] = binaries;

  const encoder = JsonEncoder.withIndent('  ');
  checksumFile.writeAsStringSync('${encoder.convert(existing)}\n');

  stdout
    ..writeln('[checksums] wrote ${checksumFile.path}')
    ..writeln('[checksums] updated $updated platform(s)');

  if (updated == 0) {
    stderr.writeln(
      '[checksums] WARNING: no binaries found in dist/binaries/. '
      'Run tool/build_binaries.sh first.',
    );
    exit(1);
  }
}

String _repoRoot() {
  var dir = Directory.current;
  while (true) {
    if (File('${dir.path}/pubspec.yaml').existsSync() == false &&
        File('${dir.path}/packages/jankdoc/pubspec.yaml').existsSync()) {
      return dir.path;
    }
    if (File('${dir.path}/.git/config').existsSync()) {
      return dir.path;
    }
    final parent = dir.parent;
    if (parent.path == dir.path) {
      // Reached filesystem root — use current directory.
      return Directory.current.path;
    }
    dir = parent;
  }
}
