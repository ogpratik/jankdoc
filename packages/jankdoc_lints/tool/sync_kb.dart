// Regenerates lib/src/agent/kb_data.dart — the JankDoc KB entries for the
// jankdoc_lints rules, for the MCP server's `explain_pattern` tool — from the
// runtime package's catalog (packages/jankdoc/lib/src/kb/kb_catalog.dart).
//
// jankdoc_lints cannot depend on `jankdoc` (a Flutter package, older Dart
// floor), so the text is copied at build time; test/kb_sync_test.dart fails
// when the copy is stale.
//
//   dart run tool/sync_kb.dart
import 'dart:io';

import 'package:analyzer/dart/analysis/utilities.dart';
import 'package:analyzer/dart/ast/ast.dart';
import 'package:analyzer/dart/ast/visitor.dart';
import 'package:jankdoc_lints/src/agent/findings.dart';

String packageRoot() => File.fromUri(Platform.script).parent.parent.path;

String catalogPath(String packageRoot) =>
    '$packageRoot/../jankdoc/lib/src/kb/kb_catalog.dart';

String generatedPath(String packageRoot) =>
    '$packageRoot/lib/src/agent/kb_data.dart';

void main() {
  final root = packageRoot();
  File(
    generatedPath(root),
  ).writeAsStringSync(generateKb(File(catalogPath(root)).readAsStringSync()));
  stdout.writeln('Wrote ${generatedPath(root)}');
}

/// The KB entries for the jankdoc_lints rules in the catalog source
/// [catalog], in the shape of `kbEntries` in kb_data.dart.
Map<String, Map<String, Object>> extractKb(String catalog) {
  final wanted = jankdocRules.values.toSet();
  final finder = _EntryFinder(wanted);
  parseString(content: catalog).unit.accept(finder);
  final missing = wanted.difference(finder.entries.keys.toSet());
  if (missing.isNotEmpty) {
    throw StateError('KB catalog has no entry for: ${missing.join(', ')}');
  }
  return {for (final id in jankdocRules.values) id: finder.entries[id]!};
}

/// The kb_data.dart source for the catalog source [catalog].
String generateKb(String catalog) {
  final entries = extractKb(catalog);

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/sync_kb.dart from')
    ..writeln('// packages/jankdoc/lib/src/kb/kb_catalog.dart — do not edit.')
    ..writeln()
    ..writeln(
      '/// JankDoc KB entries for the jankdoc_lints rules, by pattern id.',
    )
    ..writeln('const kbEntries = <String, Map<String, Object>>{');
  for (final id in jankdocRules.values) {
    final e = entries[id]!;
    out.writeln('  ${_lit(id)}: {');
    for (final key in [
      'title',
      'severity',
      'description',
      'fixGuidance',
      'expectedImprovement',
    ]) {
      out.writeln('    ${_lit(key)}: ${_lit(e[key] as String)},');
    }
    out
      ..writeln("    'sources': [")
      ..writeAll([
        for (final s in e['sources'] as List<String>) '      ${_lit(s)},\n',
      ])
      ..writeln('    ],')
      ..writeln('  },');
  }
  out.writeln('};');
  return out.toString();
}

String _lit(String s) {
  final escaped = s
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  return "'$escaped'";
}

class _EntryFinder extends RecursiveAstVisitor<void> {
  _EntryFinder(this.wanted);

  final Set<String> wanted;
  final entries = <String, Map<String, Object>>{};

  @override
  void visitMethodInvocation(MethodInvocation node) {
    // Unresolved, `KbEntry(...)` parses as a method invocation.
    if (node.methodName.name == 'KbEntry') _entry(node.argumentList);
    super.visitMethodInvocation(node);
  }

  @override
  void visitInstanceCreationExpression(InstanceCreationExpression node) {
    if (node.constructorName.type.name.lexeme == 'KbEntry') {
      _entry(node.argumentList);
    }
    super.visitInstanceCreationExpression(node);
  }

  void _entry(ArgumentList args) {
    final named = {
      for (final a in args.arguments.whereType<NamedArgument>())
        a.name.lexeme: a.argumentExpression,
    };
    final id = (named['id'] as StringLiteral?)?.stringValue;
    if (id == null || !wanted.contains(id)) return;
    String str(String name) =>
        (named[name] as StringLiteral).stringValue!.trim();
    final improvement = named['expectedImprovement'];
    entries[id] = {
      'title': str('title'),
      'severity': (named['severity'] as PrefixedIdentifier).identifier.name,
      'description': str('description'),
      'fixGuidance': str('fixGuidance'),
      'expectedImprovement': improvement is InstanceCreationExpression
          ? _namedString(improvement.argumentList, 'description')
          : improvement is MethodInvocation
          ? _namedString(improvement.argumentList, 'description')
          : '',
      'sources': [
        for (final s in (named['sources'] as ListLiteral).elements)
          (s as StringLiteral).stringValue!,
      ],
    };
  }

  static String _namedString(ArgumentList args, String name) {
    for (final a in args.arguments.whereType<NamedArgument>()) {
      if (a.name.lexeme == name) {
        return (a.argumentExpression as StringLiteral).stringValue!;
      }
    }
    return '';
  }
}
