/// JankDoc LLM baseline runner — **maintainer tool**.
///
/// Runs the LLM tier of the pipeline (Ollama + RAG + OutputValidator) against
/// [NovelFixtures], enforces the [LlmThresholds] agreed in the launch plan,
/// and writes the baseline report to `docs/llm-baseline.md`.
///
/// **This is not a public jankdoc executable.** It depends on `jankdoc_eval`,
/// which is a dev-only path dependency of `jankdoc` — so it lives under
/// `tool/` (excluded from published packages) rather than `bin/` (which pub
/// requires to use only runtime dependencies). Invoke from the workspace:
///
///     dart run packages/jankdoc/tool/llm_harness.dart \
///       --ollama-url http://127.0.0.1:11434 \
///       --model qwen2.5-coder:7b \
///       --output docs/llm-baseline.md
///
/// Exit codes:
///   0 — all three thresholds met
///   1 — one or more thresholds failed
///   2 — Ollama unreachable / setup error
library;

import 'dart:io';

import 'package:args/args.dart';
import 'package:jankdoc_core/jankdoc_core.dart';
import 'package:jankdoc_eval/jankdoc_eval.dart';

import '../lib/src/analysis/diagnosis_pipeline.dart';
import '../lib/src/analysis/ollama_provider.dart';
import '../lib/src/analysis/output_validator.dart';
import '../lib/src/analysis/vector_store_impl.dart';
import '../lib/src/kb/kb_bundle_loader.dart';
import '../lib/src/kb/kb_manager.dart';
import '../lib/src/kb/kb_seeder.dart';
import '../lib/src/session/session_repository.dart';

Future<void> main(List<String> args) async {
  final parser = ArgParser()
    ..addOption('ollama-url', defaultsTo: 'http://127.0.0.1:11434')
    ..addOption('model', defaultsTo: 'qwen2.5-coder:7b')
    ..addOption('embed-model', defaultsTo: 'nomic-embed-text')
    ..addOption('output',
        defaultsTo: 'docs/llm-baseline.md',
        help: 'Where to write the baseline markdown report.')
    ..addFlag('help', abbr: 'h', negatable: false);

  final results = parser.parse(args);
  if (results['help'] as bool) {
    stdout.writeln('JankDoc LLM baseline runner\n\n${parser.usage}');
    exit(0);
  }

  final ollamaUrl = results['ollama-url'] as String;
  final modelId = results['model'] as String;
  final embedModelId = results['embed-model'] as String;
  final outputPath = results['output'] as String;

  final llmProvider = OllamaProvider(
    baseUrl: ollamaUrl,
    modelId: modelId,
    embedModelId: embedModelId,
  );

  if (!await llmProvider.isAvailable()) {
    stderr.writeln(
      '[llm-baseline] Ollama not reachable at $ollamaUrl.\n'
      '[llm-baseline] Start Ollama and pull the required models:\n'
      '[llm-baseline]   ollama pull $modelId\n'
      '[llm-baseline]   ollama pull $embedModelId',
    );
    exit(2);
  }

  // ── Pipeline wiring ────────────────────────────────────────────────────────
  final vectorStore = InMemoryVectorStore();
  await vectorStore.load();

  final seeder = KbSeeder(vectorStore: vectorStore, llmProvider: llmProvider);
  final kbManager =
      KbManager(loader: FilesystemKbBundleLoader(), seeder: seeder);
  final kbResult = await kbManager.load();
  stdout.writeln('[llm-baseline] KB source: $kbResult');

  final validator = OutputValidator();
  final sessionRepo = SessionRepository();
  final pipeline = DiagnosisPipeline(
    ruleEngine: RuleEngine(BuiltInRuleProvider()),
    llmProvider: llmProvider,
    vectorStore: vectorStore,
    validator: validator,
    sessionRepo: sessionRepo,
  );

  // ── Run the baseline ───────────────────────────────────────────────────────
  final harness = LlmEvalHarness(
    diagnose: (batch) async {
      await for (final d in pipeline.process(batch)) {
        return d; // first diagnosis wins
      }
      return null;
    },
  );

  stdout.writeln(
    '[llm-baseline] Running ${NovelFixtures.all.length} novel fixtures…',
  );
  final report = await harness.run(NovelFixtures.all);
  stdout.writeln(report.toSummary());

  // ── Write the report ───────────────────────────────────────────────────────
  final markdown =
      _renderBaseline(report, modelId: modelId, ollamaUrl: ollamaUrl);
  await File(outputPath).writeAsString(markdown);
  stdout.writeln('[llm-baseline] Wrote $outputPath');

  // ── Cleanup + exit ─────────────────────────────────────────────────────────
  kbManager.dispose();
  await vectorStore.flush();
  sessionRepo.dispose();

  exit(report.meetsThresholds ? 0 : 1);
}

String _renderBaseline(
  LlmEvalReport report, {
  required String modelId,
  required String ollamaUrl,
}) {
  final buf = StringBuffer()
    ..writeln('# LLM Baseline')
    ..writeln()
    ..writeln('Automatically generated by `dart run jankdoc:llm_harness`.')
    ..writeln()
    ..writeln('- **Run at**: ${report.runAt.toIso8601String()}')
    ..writeln('- **Model**: `$modelId` @ $ollamaUrl')
    ..writeln('- **Cases**: ${report.total} (NovelFixtures.all)')
    ..writeln('- **Verdict**: '
        '${report.meetsThresholds ? "✓ MEETS THRESHOLDS" : "✗ BASELINE FAILED"}')
    ..writeln()
    ..writeln('## Metrics')
    ..writeln()
    ..writeln('| Metric | Result | Threshold | Status |')
    ..writeln('| :--- | ---: | ---: | :---: |')
    ..writeln('| Pattern accuracy | '
        '${(report.accuracy * 100).toStringAsFixed(1)}% | '
        '≥ ${(LlmThresholds.minAccuracy * 100).toStringAsFixed(0)}% | '
        '${report.accuracy >= LlmThresholds.minAccuracy ? "✓" : "✗"} |')
    ..writeln('| Hallucination rate | '
        '${(report.hallucinationRate * 100).toStringAsFixed(1)}% | '
        '≤ ${(LlmThresholds.maxHallucinationRate * 100).toStringAsFixed(0)}% | '
        '${report.hallucinationRate <= LlmThresholds.maxHallucinationRate ? "✓" : "✗"} |')
    ..writeln('| Median latency | '
        '${report.medianLatencyMs} ms | '
        '≤ ${LlmThresholds.maxMedianLatency.inMilliseconds} ms | '
        '${report.medianLatencyMs <= LlmThresholds.maxMedianLatency.inMilliseconds ? "✓" : "✗"} |')
    ..writeln()
    ..writeln('## Per-case results')
    ..writeln()
    ..writeln('| Case | Expected pattern | Actual pattern | Latency | Pass |')
    ..writeln('| :--- | :--- | :--- | ---: | :---: |');
  for (final c in report.cases) {
    final expected = c.assertionResults
            .map((a) => a.assertion)
            .whereType<PatternIdAssertion>()
            .map((a) => a.expectedPatternId)
            .firstOrNull ??
        '—';
    final actual = c.diagnosis?.patternId ??
        (c.error != null ? '(error)' : '(none)');
    final pass = c.passed ? '✓' : '✗';
    buf.writeln(
        '| ${c.caseId} | `$expected` | `$actual` | ${c.elapsedMs} ms | $pass |');
  }
  // Errors block for debug — critical when actual is `(error)`.
  final errored = report.cases.where((c) => c.error != null).toList();
  if (errored.isNotEmpty) {
    buf
      ..writeln()
      ..writeln('## Errors')
      ..writeln();
    for (final c in errored) {
      buf.writeln('- **${c.caseId}**: `${c.error}`');
    }
  }
  return buf.toString();
}
